function pick<T>(arr: T[], seed: number): T {
  return arr[Math.abs(seed) % arr.length];
}

function hashStr(s: string): number {
  let h = 0;
  for (let i = 0; i < s.length; i++) h = (h * 31 + s.charCodeAt(i)) | 0;
  return h;
}

export function othersLines(
  judged: EditorKey,
  placement: Placement,
  workType: WorkType | string,
  seedText: string,
): { key: EditorKey; name: string; line: string }[] {
  const seed = hashStr(seedText);
  const speakers = (["kurodo", "nina", "sol"] as Speaker[]).filter((k) => k !== judged);
  return speakers.map((sp, i) => {
    const base = BASE[`${sp}:${judged}:${placement}`] ?? ["記録しておきます。"];
    let line = pick(base, seed + i);
    const add = TYPE_ADD[`${sp}:${workType}`];
    if (add && (seed + i) % 3 === 0 && placement !== "jigo") line += pick(add, seed >> 3);
    return { key: sp, name: NAME[sp], line };
  });
}

// 判定ごとの「掲載」の言い方
export function statusLine(magazine: string, status: { kind: "cover"; slot: Placement } | { kind: "toc" } | { kind: "none" } | { kind: "sample" }): string {
  if (status.kind === "sample") return "見本の原稿なので、表紙にも目次にも載りません。";
  if (status.kind === "cover") {
    const label = { kanto: "巻頭", tokushu: "特集", kanmatsu: "巻末", namae: "", jigo: "" }[status.slot];
    return `今は${magazine}の${label}に載っています。点数の高い作品が来ると下がることがあります。`;
  }
  if (status.kind === "toc") return `表紙には載っていませんが、${magazine}の目次に名前が載っています。`;
  return "今回は載りません。";
}
