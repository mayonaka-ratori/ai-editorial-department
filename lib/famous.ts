export function normalize(s: string): string {
  return s
    .normalize("NFKC")
    .replace(/[\s　]/g, "")
    .replace(/[、。，．,.!！?？「」『』（）()\[\]【】〈〉《》"'“”‘’・…―—\-ー~〜]/g, "")
    .toLowerCase();
}

const INDEX = FAMOUS.map((f) => ({ title: f.title, key: normalize(f.head).slice(0, 22) })).filter((f) => f.key.length >= 10);

export function findFamous(text: string): { title: string } | null {
  const n = normalize(text);
  if (n.length < 10) return null;
  for (const f of INDEX) {
    if (n.includes(f.key)) return { title: f.title };
  }
  return null;
}
