export function ratioLine(counts: Record<string, number>): string {
  const total = Object.values(counts).reduce((a, b) => a + b, 0);
  if (total < 10) return "";
  const pct = (k: string) => Math.round(((counts[k] ?? 0) / total) * 100);
  return `今日ここまでのあなたの判定の割合（直近${total}件）: 巻頭${pct("kanto")}%、特集${pct("tokushu")}%、巻末${pct("kanmatsu")}%、名前だけ${pct("namae")}%、次号待ち${pct("jigo")}%。目安は巻頭10%、特集25%、巻末35%、名前だけ20%、次号待ち10%です。大きくずれていたら、この原稿の判定で少し戻してください。`;
}

export function previousLine(prev: { title: string; placement_label: string; next_request: string; revision: number }): string {
  return `この作者は今日、あなたに${prev.revision}回目の原稿を送ってきました。前回の作品名は『${prev.title}』、前回の判定は「${prev.placement_label}」、前回あなたが頼んだのは「${prev.next_request}」でした。今回のコメントでは、前回に触れて、頼んだことに応えているかどうかを1つ言ってください。前回の本文は手元にないので、作品名と判定と頼んだことだけで話します。`;
}
